"""Blocks of an arbitrary LG orbifold and its gauged group.

A block is a set S of fields such that W = W_S + W_rest with no monomial mixing S and the rest (a union of
connected components of the field graph of W), with integer c_hat(S) >= 1, so that LG_S / <J_S> is a
consistent (spectral-flow closed) block orbifold: c_hat = 1 a T^2-type block, c_hat = 2 a K3 / T^4-type block,
c_hat = 3 the whole model.  Massive fields (q = 1/2) are dropped.  Components that are not single Fermat fields
(Klein-Shepherd, D, E, loops, chains) enter the 2D fixed-point table (it only needs the charges) but the TFT
certification needs Fermat factors [missing: non-Fermat Saito / FJRW correlators]."""
import itertools
import math
from dataclasses import dataclass, field
from fractions import Fraction as Fr
from typing import List, Optional, Tuple


@dataclass
class Block:
    fields: List[int]                    # 0-based field indices, ordered by decreasing Fermat exponent
    qs: Tuple[Fr, ...]                   # R-charges of these fields
    ns: Optional[Tuple[int, ...]]        # Fermat exponents, or None if a field is not a Fermat field
    chat: Fr
    K: int                               # order of J_S
    components: List[List[int]] = field(default_factory=list)

    @property
    def fermat(self):
        return self.ns is not None

    @property
    def key(self):
        """isomorphism key for caching: sorted exponents (Fermat) or sorted charges"""
        return ("F", tuple(self.ns)) if self.fermat else ("Q", tuple(sorted(self.qs)))

    @property
    def nstates(self):
        return math.prod(n - 1 for n in self.ns) if self.fermat else None

    def label(self):
        f = "fields %s" % [i + 1 for i in self.fields]
        e = ("exponents %s" % (self.ns,)) if self.fermat else ("charges %s (non-Fermat)" % ([str(q) for q in self.qs],))
        return "%s, %s, c_hat = %s, K = %d" % (f, e, self.chat, self.K)


def charges(model):
    return [Fr(f.kcharge, model.korder) for f in model.fields]


def components(model):
    """connected components of the graph 'fields i, j appear in a common monomial of W'"""
    n = model.nfields
    parent = list(range(n))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    for t in model.superpotential:
        nz = [i for i, p in enumerate(t.powers) if p]
        for a in nz[1:]:
            parent[find(a)] = find(nz[0])
    comps = {}
    for i in range(n):
        comps.setdefault(find(i), []).append(i)
    return sorted(comps.values())


def find_blocks(model, chats=(1, 2, 3), kmax=60):
    """All unions of W-components with integer c_hat in chats.  Returns (blocks, skipped) where skipped lists
    (Block, reason) for blocks over the size guard K > kmax."""
    q = charges(model)
    comps = [c for c in components(model) if not (len(c) == 1 and q[c[0]] == Fr(1, 2))]
    cc = [sum(1 - 2 * q[i] for i in c) for c in comps]
    blocks, skipped = [], []
    for r in range(1, len(comps) + 1):
        for sub in itertools.combinations(range(len(comps)), r):
            ch = sum(cc[i] for i in sub)
            if ch.denominator != 1 or int(ch) not in chats:
                continue
            fl = [f for i in sub for f in comps[i]]
            ns = [model.fermat_exponent(f) if len(comps[i]) == 1 else None for i in sub for f in comps[i]]
            fermat = all(x is not None for x in ns)
            if fermat:
                order = sorted(range(len(fl)), key=lambda t: (-ns[t], fl[t]))
            else:
                order = sorted(range(len(fl)), key=lambda t: (q[fl[t]], fl[t]))
            fl = [fl[t] for t in order]
            qs = tuple(q[f] for f in fl)
            K = math.lcm(*[x.denominator for x in qs])
            b = Block(fl, qs, tuple(ns[t] for t in order) if fermat else None, ch, K, [comps[i] for i in sub])
            (blocks if K <= kmax else skipped).append(b if K <= kmax else (b, "K = %d > kmax = %d" % (K, kmax)))
    return blocks, skipped


def gauged_generators(model):
    """[(name, [phase per field])]: J and the extra orbifold generators of an LGOR Model."""
    gens = [("J", [Fr(f.kcharge, model.korder) for f in model.fields])]
    for j, o in enumerate(model.orders):
        gens.append(("g%d" % (j + 1), [Fr(f.charges[j], o) for f in model.fields]))
    return gens


def group_closure(gens):
    """all elements of the abelian group generated by phase vectors (Fractions mod 1)"""
    n = len(gens[0])
    e = tuple(Fr(0) for _ in range(n))
    G, frontier = {e}, [e]
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = tuple((a + b) % 1 for a, b in zip(x, g))
                if y not in G:
                    G.add(y)
                    new.append(y)
        frontier = new
    return G


def gauge_group(model):
    return group_closure([tuple(Fr(x) % 1 for x in g) for _, g in gauged_generators(model)])
