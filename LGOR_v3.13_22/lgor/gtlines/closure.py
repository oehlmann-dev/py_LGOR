"""Fusion-closure test for the group-theoretical lines of a block (``lgor gtclosure``, 3.12).

Motivation (Z6-II, 2026-11-19).  ``gtlines`` searches lines of the form Rep(G) for G = A x| Z_m with A
abelian.  The geometric orbifold predicts further lines (twist-orbit sums of non-commuting elements of
the Heisenberg group of fixed-point labels and translations) that this ansatz cannot see.  Such lines
must nevertheless appear in the fusion of the lines that *are* found.  This module

  1. builds every certified line of a block as an operator on the block chiral ring, sector by sector
     (monomial basis, grouped by charge): labelled states by their class character, unknown-basis
     sectors by M^-1 diag(chi) M;
  2. adds the invertible lines that come with them: the one-dimensional irreps of every candidate group
     and the powers of the block J_b (e^{2 pi i k q});
  3. multiplies every pair of non-invertible lines and tries to write the product as a non-negative
     integer combination of known lines with the right total quantum dimension;
  4. reports every product that does NOT decompose, with the action of the remainder on each sector.

A non-decomposable product proves that the category generated by the certified lines contains simple
lines outside the certified list [verified, given the certified lines].  The decomposition of the
remainder into simples (e.g. two lines of d = 3 rather than one of d = 6) is not decided here.
"""
from __future__ import annotations

import itertools
from collections import defaultdict
from fractions import Fraction as Fr

import numpy as np


def _charge(s, ns):
    return sum(Fr(e, n) for e, n in zip(s, ns))


def block_operators(rep, ns):
    """List of dicts {name, d, ops: {charge: (states, matrix)}} for all certified lines + invertibles."""
    from .tft import block_states
    allst = block_states(ns)
    by_q = defaultdict(list)
    for s in allst:
        by_q[_charge(s, ns)].append(s)
    lines, inv = [], []
    K = rep["K"]
    for ci, cand in enumerate(rep["candidates"]):
        if not str(cand.get("status", "")).startswith("certified"):
            continue
        SG, labels, tsec, tcls = cand["SG"], cand["labels"], cand["tsec"], cand["tcls"]
        irr = SG.irreps()
        sols = cand.get("solB") or []
        for si, sol in enumerate(sols):
            for ii, (d, ch) in enumerate(irr):
                if d == 1 and si > 0:
                    continue                      # 1-dim irreps do not depend on the orbit basis
                ops = {}
                for q, sts in by_q.items():
                    idx = {s: i for i, s in enumerate(sts)}
                    A = np.zeros((len(sts), len(sts)), complex)
                    for s in sts:
                        lab = labels.get(s)
                        if lab is not None and not isinstance(lab, tuple):
                            A[idx[s], idx[s]] = complex(ch[lab])
                    for k, ks in tsec.items():
                        if not ks or ks[0] not in idx:
                            continue
                        Mk = sol["mats"][k]
                        Mk = Mk.tolist() if hasattr(Mk, "tolist") else Mk
                        M = np.array([[complex(x) for x in row] for row in Mk])
                        D = np.diag([complex(ch[o]) for o in tcls[k]])
                        Op = np.linalg.inv(M) @ D @ M
                        for a, sa in enumerate(ks):
                            for b, sb in enumerate(ks):
                                A[idx[sa], idx[sb]] = Op[a, b]
                    ops[q] = (sts, A)
                entry = {"name": "%s irrep%d%s" % (SG.name(), ii, "" if d == 1 else " sol%d" % si), "d": d, "ops": ops,
                         "group": SG.name()}
                (inv if d == 1 else lines).append(entry)
    for k in range(1, K):
        ops = {q: (sts, np.diag([np.exp(2j * np.pi * float(k * q)) for _ in sts])) for q, sts in by_q.items()}
        inv.append({"name": "J_b^%d" % k, "d": 1, "ops": ops})
    # remove duplicate operators
    def same(a, b):
        return all(np.allclose(a["ops"][q][1], b["ops"][q][1], atol=1e-7) for q in a["ops"])
    def dedup(xs):
        out = []
        for x in xs:
            if not any(same(x, y) for y in out):
                out.append(x)
        return out
    lines, inv = dedup(lines), dedup(inv)
    # dressed lines g x L (g invertible): composites, needed to decompose products such as
    # W_h W_t = W_{ht} + eta W_{ht^-1} (eta = central quantum symmetry)
    dressed = []
    for L in lines:
        for g in inv:
            dressed.append({"name": "%s * %s" % (g["name"], L["name"]), "d": L["d"], "group": L["group"],
                            "ops": {q: (L["ops"][q][0], g["ops"][q][1] @ L["ops"][q][1]) for q in L["ops"]},
                            "dressed": True})
    full = dedup(lines + dressed)
    return full, inv


def _prod(a, b):
    return {q: (a["ops"][q][0], a["ops"][q][1] @ b["ops"][q][1]) for q in a["ops"]}


def _sum(entries, ops_keys):
    out = {}
    for q in ops_keys:
        out[q] = sum((e["ops"][q][1] for e in entries), 0)
    return out


def _vec(ops, keys):
    return np.concatenate([ops[q][1].ravel() for q in keys])


def decompose(P, D, lines, inv, max_terms=12, budget=200000):
    """Non-negative integer combination of lines+inv with total dimension D reproducing P.
    Returns (list of names) if found, "outside-span" if P is not even a real/complex linear combination of
    the known operators (this proves that new simple lines are needed), or None if undecided."""
    keys = sorted(P)
    items = lines + inv
    A = np.array([_vec(it["ops"], keys) for it in items]).T          # features x items
    b = _vec(P, keys)
    Ar = np.vstack([A.real, A.imag]); br = np.concatenate([b.real, b.imag])
    sol, res, rk, sv = np.linalg.lstsq(Ar, br, rcond=None)
    if np.linalg.norm(Ar @ sol - br) > 1e-6 * max(1.0, np.linalg.norm(br)):
        return "outside-span"
    # DFS over items (sorted by dimension, largest first), bounded budget
    order = sorted(range(len(items)), key=lambda i: -items[i]["d"])
    count = [0]
    def dfs(start, remD, acc, chosen):
        count[0] += 1
        if count[0] > budget:
            return None
        if remD == 0:
            return list(chosen) if np.allclose(acc, b, atol=1e-6) else None
        if len(chosen) >= max_terms:
            return None
        for t in range(start, len(order)):
            i = order[t]
            if items[i]["d"] > remD:
                continue
            chosen.append(i)
            r = dfs(t, remD - items[i]["d"], acc + A[:, i], chosen)
            chosen.pop()
            if r is not None:
                return r
        return None
    r = dfs(0, D, np.zeros_like(b), [])
    return [items[i]["name"] for i in r] if r is not None else None


def closure_report(ns, nmax=5):
    from .pipeline import analyse_block
    rep, txt = analyse_block(tuple(ns), nmax=nmax, a_picture=False)
    lines, inv = block_operators(rep, ns)
    out = ["FUSION CLOSURE of the certified group-theoretical lines of block %s (nmax = %d)" % (tuple(ns), nmax),
           "  non-invertible lines: %d; invertible lines used: %d (1-dim irreps of the candidate groups, powers of J_b)"
           % (len(lines), len(inv))]
    for e in lines:
        if not e.get("dressed"):
            out.append("    %-40s d = %d" % (e["name"], e["d"]))
    out.append("  (decompositions may also use the %d dressed lines g x L, g invertible)"
               % sum(1 for e in lines if e.get("dressed")))
    missing = []
    for a, b in itertools.combinations_with_replacement(range(len(lines)), 2):
        if lines[a].get("dressed") or lines[b].get("dressed"):
            continue
        if lines[a]["group"] != lines[b]["group"]:
            continue          # products across candidate groups are composite lines, not tested
        P = _prod(lines[a], lines[b])
        D = lines[a]["d"] * lines[b]["d"]
        dec = decompose(P, D, lines, inv)
        if dec == "outside-span":
            missing.append((a, b, P, D))
            out.append("  %s x %s (d = %d): OUTSIDE the span of all known lines (new simple lines needed) [verified]"
                       % (lines[a]["name"], lines[b]["name"], D))

            keys = sorted(P)
            best = min((c for c in range(len(lines)) if lines[c]["d"] < D),
                       key=lambda c: sum(np.linalg.norm(P[q][1] - lines[c]["ops"][q][1]) for q in keys), default=None)
            if best is not None:
                rem = D - lines[best]["d"]
                out.append("     remainder after removing %s (dimension %d):" % (lines[best]["name"], rem))
                for q in keys:
                    sts, A = P[q][0], P[q][1] - lines[best]["ops"][q][1]
                    if len(sts) > 1 or abs(A[0, 0] - rem) > 1e-7:
                        diag = np.allclose(A, np.diag(np.diag(A)), atol=1e-7)
                        ev = [complex(round(x.real, 4), round(x.imag, 4)) for x in np.linalg.eigvals(A)]
                        out.append("       charge %s, states %s: eigenvalues %s%s"
                                   % (q, ["x^%s" % (st,) for st in sts], ev, " (diagonal on monomials)" if diag else ""))
            continue
        if dec is None:
            missing.append((a, b, P, D))
            out.append("  %s x %s (d = %d): in the span, but no non-negative integer decomposition found (undecided)"
                       % (lines[a]["name"], lines[b]["name"], D))
        else:
            out.append("  %s x %s (d = %d) = %s" % (lines[a]["name"], lines[b]["name"], D, " + ".join(dec)))
    out.append("  RESULT: %s" % ("closed under fusion" if not missing else
                                 "%d products contain simple lines outside the certified list [verified]" % len(missing)))
    return "\n".join(out), missing
