"""Greene-Plesser mirrors of Fermat Landau-Ginzburg orbifolds and mirror checks.

For a common prime exponent the construction below over F_n is used.  For any other Fermat
W = sum_i x_i^{n_i} (mixed or non-prime exponents), ``mirror_model`` uses the
Berglund-Huebsch-Krawitz dual group: group elements are integer vectors a with phases
exp(2 pi i a_i / n_i), and the mirror group is the annihilator
H^v = { g : sum_i g_i h_i / n_i in Z for all h in H }.  LGOR sums over Z_KOrder x prod Z_N as
a direct product, so the generators are chosen independent (J first).

For W = sum_i x_i^n (all exponents equal to a prime n) and an orbifold group H of
phase symmetries (the discrete symmetries of the model, together with the R-twist
J = (1, ..., 1)), the mirror is the orbifold by the dual group

    H° = { Q in Z_n^N :  Q . Q' = 0 mod n for all Q' in H,  sum_i Q_i = 0 mod n } / <J>

(Greene-Plesser; see eq. (3.4) of Blaszczyk-Oehlmann, JHEP04(2016)068).

``mirror_check`` verifies that two computed models are mirrors of each other:
the full spectrum with all Cartan charges must agree state by state under
q- -> -q-, q^i -> -q^i (q+ unchanged), so 27 <-> 27bar; the extra gauge groups
must agree; the discrete symmetries of each side must act inside its gauge group or
match a symmetry of the other side; both must be anomaly free.
"""

from __future__ import annotations

