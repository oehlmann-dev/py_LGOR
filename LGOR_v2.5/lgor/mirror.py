def _fermat_exponent(model: Model) -> int:
    ns = set()
    for i in range(model.nfields):
        n = model.fermat_exponent(i)
        if n is None:
            raise ValueError("the Greene-Plesser mirror needs a Fermat superpotential")
        ns.add(n)
    if len(ns) != 1 or any(len([p for p in t.powers if p]) != 1 for t in model.superpotential):
        raise ValueError("the mirror construction here needs W = sum x_i^n with one common exponent n")
    n = ns.pop()
    if any(n % p == 0 for p in range(2, int(n ** 0.5) + 1)):
        raise ValueError("the mirror construction here needs a prime exponent n")
    if any(o != n for o in model.orders):
        raise ValueError(f"all discrete symmetries must be Z_{n}")
    return n


def _rank_fp(rows, p):
    rows = [[x % p for x in r] for r in rows]
    rank, ncol = 0, len(rows[0]) if rows else 0
    for c in range(ncol):
        piv = next((i for i in range(rank, len(rows)) if rows[i][c]), None)
        if piv is None:
            continue
        rows[rank], rows[piv] = rows[piv], rows[rank]
        inv = pow(rows[rank][c], -1, p)
        rows[rank] = [x * inv % p for x in rows[rank]]
        for i in range(len(rows)):
            if i != rank and rows[i][c]:
                f = rows[i][c]
                rows[i] = [(a - f * b) % p for a, b in zip(rows[i], rows[rank])]
        rank += 1
    return rank


def _kernel_fp(rows, ncol, p):
    rows = [[x % p for x in r] for r in rows]
    piv_cols, rank = [], 0
    for c in range(ncol):
        piv = next((i for i in range(rank, len(rows)) if rows[i][c]), None)
        if piv is None:
            continue
        rows[rank], rows[piv] = rows[piv], rows[rank]
        inv = pow(rows[rank][c], -1, p)
        rows[rank] = [x * inv % p for x in rows[rank]]
        for i in range(len(rows)):
            if i != rank and rows[i][c]:
                f = rows[i][c]
                rows[i] = [(a - f * b) % p for a, b in zip(rows[i], rows[rank])]
        piv_cols.append(c)
        rank += 1
    basis = []
    for f in range(ncol):
        if f in piv_cols:
            continue
        v = [0] * ncol
        v[f] = 1
        for r, c in enumerate(piv_cols):
            v[c] = (-rows[r][f]) % p
        basis.append(v)
    return basis


def _normalize(vec, p):
    v = [x % p for x in vec]
    s = sum(v)
    i = 0
    while s > 0:
        if v[i] > 0:
            v[i] -= p
            s -= p
        i = (i + 1) % len(v)
    return v


def _lcm(a, b):
    return a * b // math.gcd(a, b)


def _span(gens, n):
    S = {tuple([0] * len(n))}
    while True:
        new = S | {tuple((a + b) % m for a, b, m in zip(s, g, n)) for s in S for g in gens}
        if new == S:
            return S
        S = new


def _order(g, n):
    o = 1
    for x, m in zip(g, n):
        o = _lcm(o, m // math.gcd(x, m))
    return o


def orbifold_group(model: Model):
    """(elements as exponent vectors a with phases exp(2 pi i a_i/n_i), abstract order KOrder*prod N)
    of the phase group of a Fermat model, generated by J and the discrete symmetries."""
    n = [model.fermat_exponent(i) for i in range(model.nfields)]
    gens = [[f.kcharge * ni // model.korder for f, ni in zip(model.fields, n)]]
    for j, o in enumerate(model.orders):
        v = [f.charges[j] * ni for f, ni in zip(model.fields, n)]
        if any(x % o for x in v):
            raise ValueError(f"discrete symmetry {j + 1} does not preserve W")
        gens.append([x // o for x in v])
    ab = model.korder
    for o in model.orders:
        ab *= o
    return _span(gens, n), ab


def generator_overlap(model: Model) -> Optional[str]:
    """Warning text if J and the discrete generators are not independent (LGOR then sums over the
    group with multiplicity and overcounts the spectrum), else None.  Fermat models only."""
    if any(model.fermat_exponent(i) is None for i in range(model.nfields)):
        return None
    try:
        H, ab = orbifold_group(model)
    except ValueError:
        return None
    if len(H) != ab:
        return (f"orbifold generators are not independent: Z_{model.korder} x "
                + " x ".join(f"Z_{o}" for o in model.orders)
                + f" has order {ab} but generates a group of order {len(H)}; LGOR overcounts by {ab // len(H)}")
    return None


def general_mirror_model(model: Model, name: Optional[str] = None) -> Model:
    """BHK mirror for any Fermat W (mixed exponents allowed)."""
    n = [model.fermat_exponent(i) for i in range(model.nfields)]
    if any(x is None for x in n) or any(len([p for p in t.powers if p]) != 1 for t in model.superpotential):
        raise ValueError("the Greene-Plesser mirror needs a Fermat superpotential")
    H, _ = orbifold_group(model)
    L = 1
    for x in n:
        L = _lcm(L, x)
    dual = [g for g in product(*[range(m) for m in n])
            if all(sum(gi * hi * (L // m) for gi, hi, m in zip(g, h, n)) % L == 0 for h in H)]
    J = tuple(f.kcharge * ni // model.korder % ni for f, ni in zip(model.fields, n))
    D = set(dual)
    if J not in D:
        raise ValueError("the mirror group does not contain J (is the orbifold group inside SL?)")
    G = [list(J)]
    S = _span(G, n)
    for g in sorted(dual, key=lambda g: -_order(g, n)):
        if S == D:
            break
        T = _span(G + [list(g)], n)
        if len(T) == len(S) * _order(g, n):
            G.append(list(g))
            S = T
    if S != D:
        raise ValueError("no direct-product generating set of the mirror group with J first was found")
    orders, cols = [], []
    for g in G[1:]:
        o = _order(g, n)
        c = [x * o // m for x, m in zip(g, n)]
        c[-1] -= sum(c)          # representatives summing exactly to zero
        orders.append(o)
        cols.append(c)
    fields = [Field(f.name, f.kcharge, [c[i] for c in cols]) for i, f in enumerate(model.fields)]
    W = [SuperpotentialTerm(t.coeff, list(t.powers)) for t in model.superpotential]
    m = Model(name or f"{model.name}_mirror", model.korder, orders, fields, W)
    problems = m.check()
    if problems:
        raise ValueError("mirror model inconsistent: " + "; ".join(problems))
    return m


def mirror_model(model: Model, name: Optional[str] = None) -> Model:
    try:
        p = _fermat_exponent(model)
    except ValueError as e:
        if "Fermat superpotential" in str(e) and "common" not in str(e):
            raise
        return general_mirror_model(model, name)
    N = model.nfields
    J = [1] * N
    H = [[f.charges[j] for f in model.fields] for j in range(model.ndiscrete)]
    dual = _kernel_fp(H + [J], N, p)
    # quotient by J: keep generators independent modulo J
    gens: List[List[int]] = []
    for v in dual:
        if _rank_fp([J] + gens + [v], p) > _rank_fp([J] + gens, p):
            gens.append(v)
    gens = [_normalize(g, p) for g in gens]
    fields = [Field(f.name, f.kcharge, [g[i] for g in gens]) for i, f in enumerate(model.fields)]
    W = [SuperpotentialTerm(t.coeff, list(t.powers)) for t in model.superpotential]
    m = Model(name or f"{model.name}_mirror", model.korder, [p] * len(gens), fields, W)
    problems = m.check()
    if problems:
        raise ValueError("mirror model inconsistent: " + "; ".join(problems))
    return m


def _key_map(sym: SymmetryAnalysis, flip: bool):
    c = Counter()
    for s in sym.states:
        sgn = -1 if flip else 1
        c[(s.state.q_plus, sgn * s.state.q_minus, tuple(sgn * x for x in s.q))] += 1
    return c


def mirror_check(specA, symA: SymmetryAnalysis, specB, symB: SymmetryAnalysis) -> Tuple[bool, str]:
    from .anomalies import AnomalyAnalysis
    out = []
    tA, tB = specA.total, specB.total
    rows = [("27 <-> 27bar", (tA.n27[1], tA.n27bar[1]), (tB.n27bar[1], tB.n27[1])),
            ("chiral E6 singlets", tA.singlets[1], tB.singlets[1]),
            ("extra vector multiplets", tA.singlets[0], tB.singlets[0]),
            ("extra gauge group", symA.gauge_group, symB.gauge_group)]
    ok_all = True
    out.append(f"MIRROR CHECK   A = {specA.model.name}   B = {specB.model.name}")
    for lab, a, b in rows:
        ok = a == b
        ok_all &= ok
        out.append(f"  {lab:<28} A: {str(a):<22} B: {str(b):<22} {'ok' if ok else 'MISMATCH'}")
    kA, kB = _key_map(symA, True), _key_map(symB, False)
    same = kA == kB
    ok_all &= same
    out.append(f"  {'all states (q+, -q-, -q^i)':<28} A: {sum(kA.values()):<22} B: {sum(kB.values()):<22} "
               f"{'identical multisets' if same else 'DIFFERENT'}")
    # discrete symmetries of each side inside its own gauge group?
    for tag, sym in (("A", symA), ("B", symB)):
        for j, o in enumerate(sym.model.orders):
            inside = _discrete_in_gauge(sym, j)
            out.append(f"  {tag}: Z{o} #{j + 1} " + ("acts as an element of the extra gauge group" if inside
                                                   else "is NOT inside the gauge group"))
    ga, _ = symA.discrete_group_summary()
    gb, _ = symB.discrete_group_summary()
    ok = ga == gb
    ok_all &= ok
    out.append(f"  {'discrete group (complete, mod gauge)':<28} A: {ga:<22} B: {gb:<22} {'ok' if ok else 'MISMATCH'}")
    for tag, sym in (("A", symA), ("B", symB)):
        an = AnomalyAnalysis(sym)
        ok_all &= an.anomaly_free
        out.append(f"  {tag}: anomaly free: {'yes' if an.anomaly_free else 'NO'}")
    out.append("  RESULT: " + ("A and B are mirror pairs with identical symmetry content" if ok_all
                               else "differences found (see above)"))
    return ok_all, "\n".join(out) + "\n"


def _discrete_in_gauge(sym: SymmetryAnalysis, j: int) -> bool:
    """Is the j-th discrete charge, on all states, equal to a combination of U(1) charges mod order?"""
    o = sym.model.orders[j]
    if o > 1 and all(o % d for d in range(2, int(o ** 0.5) + 1)) and all(s.discrete[j] is not None for s in sym.states):
        # prime order: compare with all order-o gauge transformations (torus elements + E6 centre)
        st = sym.states
        qm = lambda s: s.state.q_minus
        tri = [1 if qm(s) in (Fraction(-2), Fraction(-1, 2), Fraction(1)) else
               2 if qm(s) in (Fraction(2), Fraction(1, 2), Fraction(-1)) else 0 for s in st]
        G = [[int(x) % o for x in f] for f in sym._gauge_torus_rows(st)]
        if o == 3:
            G.append(tri)
        f = [int(s.discrete[j]) % o for s in st]
        return _rank_fp(G + [f], o) == _rank_fp(G, o) if G else not any(f)
    r = len(sym.U1)
    if r == 0:
        return all((s.discrete[j] or 0) == 0 for s in sym.states)
    D = 1
    for s in sym.states:
        for x in s.u1:
            D = D * Fraction(x).denominator // __import__("math").gcd(D, Fraction(x).denominator)
    rows, rhs, seen = [], [], set()
    for s in sym.states:
        if s.discrete[j] is None:
            continue
        row = tuple(int(Fraction(x) * D) for x in s.u1)
        key = (row, int(s.discrete[j]))
        if key in seen:
            continue
        seen.add(key)
        rows.append(list(row))
        rhs.append(D * int(s.discrete[j]))
    G = len(rows)
    A = [row + [-o * D if g == i else 0 for g in range(G)] for i, row in enumerate(rows)]
    return linalg.solve_integer(A, rhs, r + G) is not None
